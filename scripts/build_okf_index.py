#!/usr/bin/env python3
"""Generate the OKF directory indexes (`index.md`) for this bundle.

    python3 scripts/build_okf_index.py [--check]

OKF §8 reserves `index.md` for navigation. An index is not a concept: it carries no `type`
and never becomes a graph node. Only the bundle root's index carries frontmatter, and only
`okf_version`.

`--check` regenerates in memory and exits 1 if anything on disk is stale, so CI can catch a
concept added without its index entry.
"""

from __future__ import annotations

import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
_DIRS: "list[pathlib.Path] | None" = None
OKF_VERSION = "0.2"
RESERVED = {"index.md", "log.md"}


def frontmatter(path: pathlib.Path) -> dict[str, str]:
    text = path.read_text(encoding="utf-8")
    if not text.startswith("---\n"):
        return {}
    end = text.find("\n---", 4)
    if end == -1:
        return {}
    out: dict[str, str] = {}
    for line in text[4:end].splitlines():
        m = re.match(r"^([a-z_]+):\s*(.+)$", line)
        if m:
            out[m.group(1)] = m.group(2).strip().strip('"')
    return out


def skill_meta(path: pathlib.Path) -> dict[str, str]:
    """A SKILL.md keeps OKF fields under `metadata.okf` — see docs/okf-conventions.md."""
    text = path.read_text(encoding="utf-8")
    out = {}
    m = re.search(r"^description: >-\n((?:  .*\n)+)", text, re.M)
    if m:
        out["description"] = " ".join(m.group(1).split())
    m = re.search(r"^    title:\s*(.+)$", text, re.M)
    if m:
        out["title"] = m.group(1).strip()
    m = re.search(r"^    type:\s*(.+)$", text, re.M)
    if m:
        out["type"] = m.group(1).strip()
    return out


def describe(path: pathlib.Path) -> tuple[str, str, str]:
    fm = skill_meta(path) if path.name == "SKILL.md" else frontmatter(path)
    return (fm.get("title", path.stem), fm.get("type", "—"), fm.get("description", ""))


def render(directory: pathlib.Path) -> str:
    rel = directory.relative_to(ROOT)
    is_root = rel == pathlib.Path(".")
    lines: list[str] = []
    if is_root:
        lines += ["---", f"okf_version: {OKF_VERSION}", "---", ""]
    lines += [f"# {'Skill registry' if is_root else rel.as_posix()}", ""]
    lines += ["<!-- Generated by scripts/build_okf_index.py — do not edit by hand. -->", ""]

    indexed = set(directories())
    subdirs = sorted(d for d in directory.iterdir() if d in indexed)
    concepts = sorted(f for f in directory.iterdir()
                      if f.is_file() and f.suffix == ".md" and f.name not in RESERVED)

    if concepts:
        lines += ["| Concept | Type | Description |", "|---|---|---|"]
        for f in concepts:
            title, typ, desc = describe(f)
            # A skill's references/ index names its files without links: a reference file points back to SKILL.md only
            # (Agent Skills: keep references one level deep).
            cell = f"{title} (`{f.name}`)" if directory.name == "references" else f"[{title}]({f.name})"
            lines.append(f"| {cell} | {typ} | {desc} |")
        lines.append("")
    if subdirs:
        lines += ["| Folder | Holds |", "|---|---|"]
        for d in subdirs:
            n = sum(1 for f in d.rglob("*.md") if f.name not in RESERVED)
            lines.append(f"| [{d.name}/]({d.name}/index.md) | {n} concept(s) |")
        lines.append("")
    return "\n".join(lines)


def directories() -> list[pathlib.Path]:
    global _DIRS
    if _DIRS is not None:
        return _DIRS
    out = [ROOT]
    for d in sorted(ROOT.rglob("*")):
        if not d.is_dir():
            continue
        parts = d.relative_to(ROOT).parts
        if any(p.startswith((".", "__")) for p in parts) or parts[0] == "scripts":
            continue
        # A directory earns an index only if it holds a concept somewhere beneath it.
        if any(f.name not in RESERVED for f in d.rglob("*.md")):
            out.append(d)
    _DIRS = out
    return out



def main(argv: list[str]) -> int:
    check = "--check" in argv
    stale: list[str] = []
    for d in directories():
        target = d / "index.md"
        want = render(d)
        have = target.read_text(encoding="utf-8") if target.exists() else None
        if have == want:
            continue
        if check:
            stale.append(str(target.relative_to(ROOT)))
        else:
            target.write_text(want, encoding="utf-8")
    if check:
        if stale:
            print("stale index(es): " + ", ".join(stale), file=sys.stderr)
            return 1
        print("indexes up to date")
        return 0
    print(f"wrote {len(directories())} index.md file(s)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
