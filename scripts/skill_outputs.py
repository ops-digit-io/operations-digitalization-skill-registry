#!/usr/bin/env python3
"""The output contract of every skill: skills*/<skill>/outputs.yaml is the source, references/outputs.md is generated from it.

    python scripts/skill_outputs.py --check      # every outputs.yaml is valid and every outputs.md is current
    python scripts/skill_outputs.py --write      # regenerate every references/outputs.md

outputs.yaml (no prose; every string is one short statement of at most 40 words):

    skill: <folder name>
    gate:                       # inputs that must exist before the first step; empty list if none
      - id: use-case
        needs: "Defined use case record"
        from: funnel-use-case   # a skill id or a role
        on_missing: "Back to funnel-use-case"
    outputs:                    # at least one
      - id: validation-record
        form: "assets/prototype-validation-record.md, filled"
        template: assets/prototype-validation-record.md      # optional, must exist
        to_skills: [bc-build]                                 # skill ids (may be empty if to_roles is set)
        to_roles: ["plant representative"]                    # roles, never persons
        done_when:                                            # at least one criterion; each needs evidence in the run record
          - "The result is passed, failed or inconclusive"
        check:                                                # optional automatic check: a command ({file} is the output file)
          cmd: "python scripts/check_x.py {file}"             # or: structure: true  (the output keeps the template's sections, no open placeholder)
        signoff: "plant representative"                       # optional human sign-off (a role)
    receives_from: [funnel-use-case]                          # skill ids
    next:                                                     # where the result goes
      - when: "passed"
        to: [bc-build]
    stops_when:                                               # at least one
      - "No pass criterion exists"

Every output needs a check or a signoff: an output nobody can check is not an output. scripts/run_record.py turns this file
into the checklist of one call and refuses to close a run whose criteria have no evidence.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parent))
import skillpaths as skp  # noqa: E402

MAX_WORDS = 40
ID = re.compile(r"^[a-z0-9][a-z0-9-]{0,47}$")
GENERATED = "<!-- Generated by scripts/skill_outputs.py from outputs.yaml: do not edit by hand. -->"


def words(s) -> int:
    return len(str(s).split())


def load(skill_dir: Path):
    p = skill_dir / "outputs.yaml"
    return yaml.safe_load(p.read_text(encoding="utf-8")) if p.is_file() else None


def _strings(path, value, errs):
    if not isinstance(value, str) or not value.strip():
        errs.append(f"{path}: must be a non-empty string")
    elif words(value) > MAX_WORDS:
        errs.append(f"{path}: {words(value)} words, at most {MAX_WORDS} (this is a statement, not prose)")


def validate(name: str, data, skill_dir: Path, ids: set[str]) -> list[str]:
    errs: list[str] = []
    if not isinstance(data, dict):
        return [f"{name}/outputs.yaml: missing or not a mapping"]
    if data.get("skill") != name:
        errs.append(f"{name}/outputs.yaml: skill must be '{name}'")
    for key in ("gate", "outputs", "receives_from", "next", "stops_when"):
        if not isinstance(data.get(key), list):
            errs.append(f"{name}/outputs.yaml: '{key}' must be a list (empty if there is none)")
    if errs:
        return errs
    seen: set[str] = set()
    for i, g in enumerate(data["gate"]):
        p = f"{name}/outputs.yaml gate[{i}]"
        if not isinstance(g, dict) or not ID.match(str(g.get("id", ""))):
            errs.append(f"{p}: needs an id (lowercase, digits, hyphens)")
            continue
        for k in ("needs", "on_missing"):
            _strings(f"{p}.{k}", g.get(k), errs)
        if g.get("from") is not None:
            _strings(f"{p}.from", g.get("from"), errs)
    if not data["outputs"]:
        errs.append(f"{name}/outputs.yaml: at least one output")
    for i, o in enumerate(data["outputs"]):
        p = f"{name}/outputs.yaml outputs[{i}]"
        if not isinstance(o, dict) or not ID.match(str(o.get("id", ""))):
            errs.append(f"{p}: needs an id (lowercase, digits, hyphens, at most 48 characters)")
            continue
        if o["id"] in seen:
            errs.append(f"{p}: duplicate id '{o['id']}'")
        seen.add(o["id"])
        p = f"{name}/outputs.yaml output '{o['id']}'"
        _strings(f"{p}.form", o.get("form"), errs)
        if o.get("template") and not (skill_dir / o["template"]).is_file():
            errs.append(f"{p}: template '{o['template']}' does not exist")
        to_skills, to_roles = o.get("to_skills"), o.get("to_roles")
        if not isinstance(to_skills, list) or not isinstance(to_roles, list):
            errs.append(f"{p}: to_skills and to_roles must be lists")
        else:
            if not to_skills and not to_roles:
                errs.append(f"{p}: needs a recipient (a skill or a role)")
            for t in to_skills:
                if t not in ids:
                    errs.append(f"{p}: to_skills names '{t}', which is not a skill")
            for r in to_roles:
                _strings(f"{p}.to_roles", r, errs)
        dw = o.get("done_when")
        if not isinstance(dw, list) or not dw:
            errs.append(f"{p}: done_when needs at least one criterion")
        else:
            for c in dw:
                _strings(f"{p}.done_when", c, errs)
        chk, sig = o.get("check"), o.get("signoff")
        if not chk and not sig:
            errs.append(f"{p}: needs a check (a command) or a signoff (a role): an unchecked output is not an output")
        if chk is not None:
            ok_cmd = isinstance(chk, dict) and "{file}" in str(chk.get("cmd", ""))
            ok_struct = isinstance(chk, dict) and chk.get("structure") is True and bool(o.get("template"))
            if not (ok_cmd or ok_struct):
                errs.append(f"{p}: check needs cmd (with {{file}}) or structure: true (which needs a template)")
        if sig is not None:
            _strings(f"{p}.signoff", sig, errs)
    for t in data["receives_from"]:
        if t not in ids:
            errs.append(f"{name}/outputs.yaml: receives_from names '{t}', which is not a skill")
    for n in data["next"]:
        if not isinstance(n, dict) or not isinstance(n.get("to"), list):
            errs.append(f"{name}/outputs.yaml: every next entry needs when and to (a list of skills)")
            continue
        _strings(f"{name}/outputs.yaml next.when", n.get("when"), errs)
        for t in n["to"]:
            if t not in ids:
                errs.append(f"{name}/outputs.yaml: next names '{t}', which is not a skill")
    if not data["stops_when"]:
        errs.append(f"{name}/outputs.yaml: stops_when needs at least one condition")
    for s in data["stops_when"]:
        _strings(f"{name}/outputs.yaml stops_when", s, errs)
    return errs


def _tick(x: str) -> str:
    return f"`{x}`"


def render(name: str, data: dict) -> str:
    out = ["---", "type: Skill Reference", "title: Outputs",
           f"description: The outputs {name} must deliver, who receives each one, and what makes each complete. Generated from outputs.yaml.",
           "resource: ../SKILL.md", "status: draft", "tags: [outputs, handoff]", "---", "# Outputs", "", GENERATED, "",
           "## Required outputs", "", "| Output | Form | Recipient | Complete when |", "|---|---|---|---|"]
    for o in data["outputs"]:
        rec = ", ".join([_tick(s) for s in o["to_skills"]] + list(o["to_roles"]))
        how = "; ".join(o["done_when"])
        out.append(f"| {o['id']} | {o['form']} | {rec} | {how} |")
    if data["gate"]:
        out += ["", "## Gate", "", "| Gate item | Needs | From | If missing |", "|---|---|---|---|"]
        for g in data["gate"]:
            out.append(f"| {g['id']} | {g['needs']} | {g.get('from') or ''} | {g['on_missing']} |")
    out += ["", "## Checks", "", "| Output | Check | Sign-off |", "|---|---|---|"]
    for o in data["outputs"]:
        chk = o.get("check") or {}
        how = f"`{chk['cmd']}`" if chk.get("cmd") else (f"structure of `{o['template']}`" if chk.get("structure") else "manual")
        out.append(f"| {o['id']} | {how} | {o.get('signoff') or 'none'} |")
    out += ["", "## Handoff", ""]
    if data["receives_from"]:
        out.append("- **Receives from:** " + ", ".join(_tick(s) for s in data["receives_from"]))
    for n in data["next"]:
        out.append(f"- **Next:** {n['when']}: " + ", ".join(_tick(s) for s in n["to"]))
    for s in data["stops_when"]:
        out.append(f"- **Stops here when:** {s}")
    return "\n".join(out) + "\n"


def main(argv: list[str]) -> int:
    ids = set(skp.all_ids())
    errors: list[str] = []
    stale: list[str] = []
    for name in sorted(ids):
        d = skp.skill_dir(name)
        data = load(d)
        errs = validate(name, data, d, ids)
        errors += errs
        if errs:
            continue
        text = render(name, data)
        target = d / "references" / "outputs.md"
        if "--write" in argv:
            target.parent.mkdir(exist_ok=True)
            target.write_text(text, encoding="utf-8", newline="\n")
        elif not target.is_file() or target.read_text(encoding="utf-8").replace("\r\n", "\n") != text:
            stale.append(name)
    for e in errors:
        print(f"  - {e}", file=sys.stderr)
    for n in stale:
        print(f"  - {n}/references/outputs.md is stale: run python scripts/skill_outputs.py --write", file=sys.stderr)
    if errors or stale:
        print(f"FAIL: {len(errors)} output-contract problem(s), {len(stale)} stale file(s)", file=sys.stderr)
        return 1
    print(f"OK: {len(ids)} skills, every output has a criterion and a check or sign-off")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
