#!/usr/bin/env python3
"""Generate docs/new-state-skill-map.md: every core skill mapped onto the new-state process flow (extension skills are left out).

    python scripts/build_new_state_skill_map.py            # write the page
    python scripts/build_new_state_skill_map.py --check    # fail if the page is stale

Inputs: docs/new-state/process.yaml (lanes, steps, skills), registry.yaml (state, tier), and the four New-State files in docs/new-state/
(to say which file names which skill). The interactive version of the same data is built by scripts/build_site.py.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
import skillpaths as skp
OUT = ROOT / "docs" / "new-state-skill-map.md"
FILES = {"Flow": "OD_NewState_Flow.mermaid", "Process flow": "OD_NewState_ProcessFlow.html", "BPMN": "OD_NewState_BPMN.html", "VSM": "OD_NewState_VSM_SkillMap.html"}


def render() -> str:
    proc = yaml.safe_load((ROOT / "docs/new-state/process.yaml").read_text(encoding="utf-8"))
    reg = {s["id"]: s for s in yaml.safe_load((ROOT / "registry.yaml").read_text(encoding="utf-8"))["skills"] if s.get("library") == "core"}
    text = {k: (ROOT / "docs/new-state" / v).read_text(encoding="utf-8") for k, v in FILES.items()}
    named = {s: [k for k, t in text.items() if re.search(r"(?<![\w-])" + re.escape(s) + r"(?![\w-])", t)] for s in reg}

    def link(s: str) -> str:
        mark = " *(draft)*" if reg[s].get("status") == "draft" else ""
        return f"[`{s}`](../{skp.folder_of(s)}/{s}/SKILL.md){mark}"

    where: dict[str, list[str]] = {s: [] for s in reg}
    L = ["---", "type: Map of Content", "title: New-state skill map",
         'description: "Every core skill mapped onto the new-state process flow: which step it serves and in which of the four New-State files it appears. Extension skills are not listed."',
         "status: draft", "owner: human:jakob.gabriel", "tags: [process-flow, lanes, skill-map]",
         "generated: { by: claude-code/1, at: 2026-11-05T00:00:00Z }", "---",
         "<!-- Generated by scripts/build_new_state_skill_map.py from docs/new-state/process.yaml - do not edit by hand. -->",
         "# New-state skill map", "",
         "The process flow with the core skills that serve each step. The interactive version, with "
         "downloads per lane, is the process map of the documentation site (`python scripts/build_site.py`).", ""]

    def section(title, who, summary, branches, level="##"):
        L.extend([f"{level} {title}", "", f"*{who}.* {summary}", ""])
        for b in branches:
            if b.get("title"):
                L.extend([f"**{b['title']}**", ""])
            L.extend(["| Step | Skills | Wait |", "|---|---|---|"])
            for st in b["steps"]:
                for s in st.get("skills", []):
                    where[s].append(f"{title}: {st['title']}")
                L.append(f"| {st['title']} | {', '.join(link(s) for s in st.get('skills', [])) or '-'} | {st.get('wait', '-')} |")
            L.append("")

    i = proc["intake"]
    section(i["title"], i["who"], i["summary"], [{"steps": i["steps"]}])
    for lane in proc["lanes"]:
        section(lane["title"], lane["who"], lane["summary"], lane["branches"])

    sp = proc["spine"]
    L.extend([f"## {sp['title']}", "", sp["summary"], "", "| Skills |", "|---|", f"| {', '.join(link(s) for s in sp.get('skills', [])) or '-'} |", ""])
    for s in sp.get("skills", []):
        where[s].append(sp["title"])

    L.extend(["## All skills", "", f"{len(reg)} core skills. 'Files' lists which of the four New-State files name the skill.", "",
              "| Skill | State | Tier | Steps | Files |", "|---|---|---|---|---|"])
    for s in sorted(reg):
        st = "draft" if reg[s].get("status") == "draft" else "in use"
        steps = "; ".join(dict.fromkeys(where[s])) or "-"
        L.append(f"| {link(s)} | {st} | {reg[s].get('tier', '')} | {steps} | {', '.join(named[s]) or 'none'} |")
    L.append("")
    return "\n".join(L)


if __name__ == "__main__":
    new = render()
    if "--check" in sys.argv:
        cur = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if cur.replace("\r\n", "\n") != new:
            print(f"stale: {OUT.relative_to(ROOT)}")
            raise SystemExit(1)
        print("new-state skill map up to date")
    else:
        OUT.write_text(new, encoding="utf-8", newline="\n")
        print(f"wrote {OUT.relative_to(ROOT)}")
