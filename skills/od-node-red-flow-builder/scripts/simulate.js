#!/usr/bin/env node
/*
 simulate.js - dry-run a flow generated by build_flow.py without Node-RED.

 Usage: node simulate.js flow.json batches.json

 batches.json = array of batches; each batch = array of packets as they come out
 of DecodeProto, e.g.
   [[{"uuid":"<in-uuid>","valueInteger":"345","isDelta":true}], [...]]
 sysTime may be given in unix ms (default: now). Simulates:
 config -> filter uuids -> split -> store (switch/change) -> calculate -> rbe -> print.
*/
const fs = require('fs');
const [flowFile, batchFile] = process.argv.slice(2);
if (!flowFile || !batchFile) { console.error('usage: node simulate.js flow.json batches.json'); process.exit(1); }
const flowNodes = JSON.parse(fs.readFileSync(flowFile, 'utf8'));
const batches = JSON.parse(fs.readFileSync(batchFile, 'utf8'));
const byName = n => flowNodes.find(x => x.name === n);
const store = {};
const flow = { get: k => store[k], set: (k, v) => { if (v === undefined) delete store[k]; else store[k] = v; } };
const node = { warn: m => console.log('  [warn]', m), error: m => console.log('  [error]', m), log: console.log };
const run = (fnNode, msg) => new Function('msg', 'flow', 'node', 'context', 'global', 'env', 'RED', fnNode.func)
  (msg, flow, node, { get: () => undefined, set: () => {} }, flow, { get: () => undefined }, {});
const getPath = (o, p) => p.split('.').reduce((a, k) => (a == null ? undefined : a[k]), o);

// 1. config
const cfg = byName('Set flow config');
for (const r of cfg.rules) if (r.pt === 'flow' && r.t === 'set') store[r.p] = r.to;
run(byName('set datapointConfigFilter'), {});
const lk = flowNodes.find(n => n.type === 'template' && n.name === 'mapping table');
if (lk) {
  const csv = flowNodes.find(n => n.type === 'csv');
  const cols = csv.temp.split(',');
  const sep = csv.sep === '\\t' ? '\t' : csv.sep;
  store.lookupTable = lk.template.split('\n').filter(Boolean).map(l => {
    const p = l.split(sep); const o = {}; cols.forEach((c, i) => o[c] = p[i]); return o;
  });
}
const sw = flowNodes.find(n => n.type === 'switch' && n.name === 'uuid filter per input');
const calc = flowNodes.find(n => n.type === 'function' && n.name.startsWith('calculate '));
const rbe = flowNodes.find(n => n.type === 'rbe');
const stores = sw.wires.map(w => flowNodes.find(n => n.id === w[0]));
let lastRbe;

batches.forEach((batch, bi) => {
  console.log(`batch ${bi + 1}: ${batch.map(p => p.uuid.slice(0, 8)).join(', ')}`);
  let m = run(byName('filter uuids'), { payload: { plcPackets: batch.map(p => ({ sysTime: Date.now(), ...p })) } });
  if (!m) { console.log('  (filtered out - no relevant uuid)'); return; }
  m.payload.forEach((pkt, idx) => {
    const msg = { payload: JSON.parse(JSON.stringify(pkt)), parts: { index: idx, count: m.payload.length } };
    const k = sw.rules.findIndex(r => store[r.v] === msg.payload.uuid);
    if (k < 0) return;
    for (const r of stores[k].rules) store[r.p] = getPath(msg, r.to);
    const out = run(calc, msg);
    if (!out) return;
    const field = Object.keys(out.payload)[0];
    const val = out.payload[field];
    if (rbe && JSON.stringify(val) === JSON.stringify(lastRbe)) { console.log(`  -> ${field}=${JSON.stringify(val)} (unchanged, dropped by rbe)`); return; }
    lastRbe = val;
    const outVar = byName('format msg.payload').rules.find(r => r.p === 'payload.uuid').to;
    console.log(`  -> PUBLISH uuid=${store[outVar]} ${field}=${JSON.stringify(val)}`);
  });
});
